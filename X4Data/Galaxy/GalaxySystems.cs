using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;

namespace X4Data.Galaxy;

/// <summary>
/// AI step 3 (docs/plan_galaxy_editor_ai.md, finding B): many vanilla MD scripts run ONLY in the X4 galaxy, they check
/// "player.galaxy.macro == macro.xu_ep2_universe_macro" (or .ismacro.{...}). In an own galaxy the faction AI, the
/// economy helpers and the generic missions therefore never start. For each switched-on group this writes a small diff
/// per script that changes such a check to "the X4 galaxy OR ours": the X4 galaxy behaves as before.
///
/// Chosen from a scan of the base game and all DLCs (2026-11-22, probe mode "galaxychecks"): only scripts that name no
/// vanilla sector. Stories, tutorials, placed objects, the DLC setup blocks (Heretic's End, Solar System, ...) stay off:
/// they look for vanilla sectors (one with required="true").
/// </summary>
public static class GalaxySystems
{
    /// <summary>(group, script, cues); cues null = every check in the script.</summary>
    public static readonly (string Group, string File, string[]? Cues)[] Scripts =
    {
        // faction AI: managers (expansion, defence, building), station upkeep, trade drain, reputation, patrol jobs
        ("factionai", "md/factionlogic.xml", null),
        ("factionai", "md/finalisestations.xml", null),
        ("factionai", "md/drain_stations.xml", null),
        ("factionai", "md/playerreputation.xml", null),
        ("factionai", "md/setup.xml", new[] { "Start" }),
        // generic missions and guild missions (mission offers at stations)
        ("missions", "md/gmc_dynamic.xml", null),
        ("missions", "md/gm_rescue_ship.xml", null),
        ("missions", "md/x4ep1_war_subscriptions.xml", null),
        ("missions", "md/x4ep1_trade_subscriptions.xml", null),
        ("missions", "md/x4ep1_pirates_subscriptions.xml", null),
        // Kha'ak raids (nests and attacks; their vanilla sectors are not found in an own galaxy)
        ("khaak", "md/khaak_activity.xml", null),
    };

    public static readonly (string Group, string Label, string Tip)[] Groups =
    {
        ("factionai", "Faction AI and economy", "The factions' managers run in this galaxy: they build and extend stations, defend and expand their sectors, "
            + "trade and send patrols, as in the X4 galaxy. Without it the stations of the game start stay as they are and no faction acts."),
        ("missions", "Missions", "Generic missions at stations and the guild missions (war, trade, pirates)."),
        ("khaak", "Kha'ak raids", "Kha'ak nests and raids into the factions' sectors, as in the X4 galaxy. Off by default: "
            + "their vanilla home sectors do not exist here, so where they appear is not tested yet."),
    };

    static readonly Regex IsMacro = new(@"player\.galaxy\.macro\.ismacro\.\{macro\.xu_ep2_universe_macro\}");
    static readonly Regex Equals = new(@"player\.galaxy\.macro\s*==\s*macro\.xu_ep2_universe_macro");

    /// <summary>The condition with "or our galaxy" added to every X4 galaxy check; null if it has none.</summary>
    public static string? Widen(string value, string ourGalaxyMacro)
    {
        var v = IsMacro.Replace(value, m => $"({m.Value} or player.galaxy.macro.ismacro.{{macro.{ourGalaxyMacro}}})");
        v = Equals.Replace(v, m => $"({m.Value} or player.galaxy.macro == macro.{ourGalaxyMacro})");
        return v == value ? null : v;
    }

    /// <summary>
    /// Diff files (mod path -> text) for the switched-on groups. script: the game's script (DLC diffs applied), null =
    /// not in the game. Selectors name the cue and the condition's own text, never a position, so other diffs before
    /// ours do not break them; a check whose text is not unique in its cue is left out (and reported in notes).
    /// </summary>
    public static Dictionary<string, string> Diffs(IEnumerable<string> groups, string ourGalaxyMacro, Func<string, XDocument?> script, List<string>? notes = null)
    {
        var on = groups.ToHashSet();
        var files = new Dictionary<string, string>();
        foreach (var (_, file, cues) in Scripts.Where(s => on.Contains(s.Group)))
        {
            var doc = script(file);
            if (doc?.Root == null) { notes?.Add($"{file}: not in the game, skipped"); continue; }
            var x = new StringBuilder("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by X4 Map Editor: this script also runs in the galaxy of the mod (the X4 galaxy as before). -->\n<diff>\n");
            int n = 0;
            foreach (var cue in doc.Root.Descendants().Where(e => e.Name.LocalName is "cue" or "library" && e.Attribute("name") != null))
            {
                string name = (string)cue.Attribute("name")!;
                if (cues != null && !cues.Contains(name)) continue;
                // checks of this cue itself, not of the cues inside it (they get their own selector)
                var own = cue.Descendants().Where(e => e.Attribute("value") is { } a && a.Value.Contains("xu_ep2_universe_macro")
                                                       && e.Ancestors().First(a2 => a2.Name.LocalName is "cue" or "library") == cue).ToList();
                foreach (var e in own)
                {
                    var value = e.Attribute("value")!.Value;
                    var wide = Widen(value, ourGalaxyMacro);
                    if (wide == null) continue;
                    if (cue.Descendants(e.Name).Count(o => (string?)o.Attribute("value") == value) != 1)
                    {
                        notes?.Add($"{file}: cue {name}: the check \"{value}\" is there more than once, left as it is");
                        continue;
                    }
                    string q = value.Contains('\'') ? "&quot;" : "'";
                    x.Append($"  <replace sel=\"//{cue.Name.LocalName}[@name='{Xa(name)}']//{e.Name.LocalName}[@value={q}{Xa(value)}{q}]/@value\">{Xt(wide)}</replace>\n");
                    n++;
                }
            }
            if (n > 0) files[file] = x.Append("</diff>\n").ToString();
        }
        return files;
    }

    static string Xa(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace("\"", "&quot;");
    static string Xt(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
